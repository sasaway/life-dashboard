// 타이머를 다는 단계: 불을 쓰고 시간이 정해진 단계
export const hasTimer = (step) => HEATS[step.heat].fire && step.sec > 0;

// 전체 걸리는 시간(분). 시간이 안 적힌 손질 단계는 1분으로 친다.
export function totalMinutes(recipe) {
  const sec = recipe.steps.reduce((sum, st) => sum + (st.sec || 60), 0);
  return Math.round(sec / 60);
}

export function mmss(sec) {
  const s = Math.max(0, Math.ceil(sec));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;
}
